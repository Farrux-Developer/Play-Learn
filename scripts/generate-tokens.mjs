import { formatHex, oklch, wcagContrast } from 'culori';

const ANCHORS = {
  paper: '#F6F3EA',
  ink: '#0F1E3A',
  blueprint: '#0B3566',
  cobalt: '#0F4C81',
  chalk: '#EAF2FF',
  saffron: '#F5A800',
  glaze: '#19B7A6',
  coral: '#E4572E',
};

function tuneForContrast(baseHex, bgHex, minRatio, direction) {
  const base = oklch(baseHex);
  const current = { ...base };
  for (let i = 0; i < 60; i += 1) {
    const candidateHex = formatHex(current);
    if (wcagContrast(candidateHex, bgHex) >= minRatio) {
      return candidateHex.toUpperCase();
    }
    current.l = Math.max(0.08, Math.min(0.95, current.l + direction * 0.015));
  }
  return formatHex(current).toUpperCase();
}

function deriveSurfaceScale() {
  const paperBase = oklch(ANCHORS.paper);
  const paperRaised = formatHex({ ...paperBase, l: Math.min(0.992, paperBase.l + 0.032), c: paperBase.c * 0.55 }).toUpperCase();
  const paperInset = formatHex({ ...paperBase, l: paperBase.l - 0.055, c: paperBase.c * 1.45 }).toUpperCase();
  const inkMuted = tuneForContrast('#4B5C78', ANCHORS.paper, 7.0, -1);

  const bpBase = oklch(ANCHORS.blueprint);
  const bpDeep = formatHex({ ...bpBase, l: Math.max(0.18, bpBase.l - 0.08), c: bpBase.c * 0.92 }).toUpperCase();
  const bpRaised = formatHex({ ...bpBase, l: Math.min(0.42, bpBase.l + 0.065), c: bpBase.c * 0.95 }).toUpperCase();
  const chalkMuted = tuneForContrast('#B6CCE8', bpRaised, 5.2, 1);

  const cobaltDepth = formatHex({ ...oklch(ANCHORS.cobalt), l: oklch(ANCHORS.cobalt).l - 0.12 }).toUpperCase();
  const saffronDepth = formatHex({ ...oklch(ANCHORS.saffron), l: oklch(ANCHORS.saffron).l - 0.2 }).toUpperCase();
  const glazeDepth = formatHex({ ...oklch(ANCHORS.glaze), l: oklch(ANCHORS.glaze).l - 0.17 }).toUpperCase();
  const coralDepth = formatHex({ ...oklch(ANCHORS.coral), l: oklch(ANCHORS.coral).l - 0.17 }).toUpperCase();

  // WCAG AA (>= 4.5:1) semantic text variants on both surfaces
  const okInkPaper = tuneForContrast(ANCHORS.glaze, paperRaised, 5.4, -1);
  const warnInkPaper = tuneForContrast(ANCHORS.coral, paperRaised, 5.2, -1);
  const rewardInkPaper = tuneForContrast(ANCHORS.saffron, paperRaised, 4.8, -1);

  const okInkBlueprint = tuneForContrast(ANCHORS.glaze, bpRaised, 5.6, 1);
  const warnInkBlueprint = tuneForContrast(ANCHORS.coral, bpRaised, 5.4, 1);
  const rewardInkBlueprint = tuneForContrast(ANCHORS.saffron, bpRaised, 4.8, 1);

  return {
    paperRaised,
    paperInset,
    inkMuted,
    bpDeep,
    bpRaised,
    chalkMuted,
    cobaltDepth,
    saffronDepth,
    glazeDepth,
    coralDepth,
    okInkPaper,
    warnInkPaper,
    rewardInkPaper,
    okInkBlueprint,
    warnInkBlueprint,
    rewardInkBlueprint,
  };
}

