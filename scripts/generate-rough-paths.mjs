/**
 * Build-time Rough.js chalk stroke generator.
 * Produces deterministic, zero-runtime-cost SVG path strings for:
 *  - Blueprint HUD outer chalk border (A01 / A15)
 *  - Xarita city-to-city trail (A16)
 *  - Soft coral error hand-drawn underline (A18)
 *  - Verification checkmark stroke (A18)
 */
import fs from 'node:fs';
import path from 'node:path';
import rough from 'roughjs';

const gen = rough.generator();

function drawableToPathD(drawable) {
  const opsList = [];
  for (const set of drawable.sets) {
    if (set.type !== 'path') continue;
    let d = '';
    for (const item of set.ops) {
      const data = item.data;
      if (item.op === 'move') {
        d += `M${data[0].toFixed(1)} ${data[1].toFixed(1)} `;
      } else if (item.op === 'lineTo') {
        d += `L${data[0].toFixed(1)} ${data[1].toFixed(1)} `;
      } else if (item.op === 'bcurveTo') {
        d += `C${data[0].toFixed(1)} ${data[1].toFixed(1)}, ${data[2].toFixed(1)} ${data[3].toFixed(1)}, ${data[4].toFixed(1)} ${data[5].toFixed(1)} `;
      }
    }
    if (d.trim()) opsList.push(d.trim());
  }
  return opsList;
}

// 1. Blueprint HUD beveled/rounded chalk frame (viewBox 0 0 480 620)
const hudRect = gen.path(
  'M 24 8 H 456 L 472 24 V 596 L 456 612 H 24 L 8 596 V 24 Z',
  {
    roughness: 0.68,
    bowing: 0.85,
    seed: 42,
    strokeWidth: 2,
    disableMultiStroke: true,
  }
);

// 2. Xarita chalk trail connecting Samarqand (90,52) -> Buxoro (400,48) -> Toshkent (710,42)
const xaritaTrail = gen.path(
  'M 90 52 C 230 16, 310 82, 400 48 C 490 14, 580 76, 710 42',
  {
    roughness: 0.72,
    bowing: 0.9,
    seed: 108,
    strokeWidth: 3.5,
    disableMultiStroke: true,
  }
);

// 3. Hand-drawn soft error underline (viewBox 0 0 240 14)
const errorUnderline = gen.path('M 4 8 Q 62 3, 120 8 T 236 7', {
  roughness: 0.82,
  bowing: 1.0,
  seed: 17,
  strokeWidth: 2.2,
  disableMultiStroke: true,
});

// 4. Tactile checkmark stroke (viewBox 0 0 28 24)
const checkMark = gen.path('M 5 12.5 L 11.2 18.5 L 23 6.5', {
  roughness: 0.58,
  bowing: 0.6,
  seed: 9,
  strokeWidth: 2.6,
  disableMultiStroke: true,
});

const out = `/* AUTO-GENERATED by scripts/generate-rough-paths.mjs (Rough.js build-time paths) */
export const ROUGH_PATHS = {
  hudFrame: ${JSON.stringify(drawableToPathD(hudRect)[0] ?? '')},
  xaritaTrail: ${JSON.stringify(drawableToPathD(xaritaTrail)[0] ?? '')},
  errorUnderline: ${JSON.stringify(drawableToPathD(errorUnderline)[0] ?? '')},
  checkMark: ${JSON.stringify(drawableToPathD(checkMark)[0] ?? '')},
} as const;
`;

fs.mkdirSync(path.resolve('lib/motion'), { recursive: true });
fs.writeFileSync(path.resolve('lib/motion/roughPaths.ts'), out, 'utf8');
console.log('Generated lib/motion/roughPaths.ts');
